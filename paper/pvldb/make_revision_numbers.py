        f"\\newcommand{{\\Nrevwilson}}{{{wilson_upper(0, search['n_targets']):.1f}}}",
        f"\\newcommand{{\\Nrevpairsum}}{{{pair['defenses']['none']['sum_matches_two_balances']}}}",
        f"\\newcommand{{\\Nrevpairexact}}{{{pair['defenses']['none']['either_customer_exact']}}}",
        f"\\newcommand{{\\Nrevfloattrials}}{{{unit['trials'] + join['trials']}}}",
