        f"\\newcommand{{\\Nrevstatelesskfivebis}}{{{search['defenses']['stateless_k5']['bisection_narrowed']}}}",
        f"\\newcommand{{\\Nrevstatelesskten}}{{{search['defenses']['stateless_k10']['exact_recovery']}}}",
        f"\\newcommand{{\\Nrevstatelessktenbis}}{{{search['defenses']['stateless_k10']['bisection_narrowed']}}}",
        f"\\newcommand{{\\Nrevpairwisekthree}}{{{search['defenses']['pairwise_k3']['exact_recovery']}}}",
