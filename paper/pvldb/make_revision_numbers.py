    flat = []

    def walk(x):
        if isinstance(x, dict) and "check_ms" in x:
            flat.append(x)
        elif isinstance(x, list):
            for y in x:
                walk(y)

    walk(e2e["direct"])
    checks = [q["check_ms"] for q in flat]
    executed = [q for q in flat if q.get("execute_ms") is not None]

