        f"\\newcommand{{\\Nrevduckms}}{{{scale['latency']['aggregated_key_weights_in_db']['median_ms']:.1f}}}",
        f"\\newcommand{{\\Nrevduckmax}}{{{scale['history']['max_total_ms']:.2f}}}",
        f"\\newcommand{{\\Nrevduckhist}}{{{scale['history']['queries']}}}",
