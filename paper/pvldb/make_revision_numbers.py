ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "experiments" / "results" / "purpose_sql"
OUT = Path(__file__).resolve().parent / "revision_numbers.tex"


def wilson_upper(k: int, n: int, z: float = 1.96) -> float:
    p = k / n
    denom = 1 + z ** 2 / n
    centre = p + z ** 2 / (2 * n)
    margin = z * ((p * (1 - p) / n + z ** 2 / (4 * n ** 2)) ** 0.5)
    return 100 * (centre + margin) / denom


def main() -> None:
    search = json.loads((RES / "attack_search.json").read_text())
    pair = json.loads((RES / "pair_sum_probe.json").read_text())
    tol = json.loads((RES / "float_tolerance.json").read_text())
    scale = json.loads((RES / "scale_duckdb.json").read_text())
